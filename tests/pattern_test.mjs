import assert from 'node:assert/strict';
import P from '../build/Pattern.mjs';
import L from '../build/Logic.mjs';
const v=id=>({$:'EVar',id}), n=expr=>({$:'ENot',expr}),a=(left,right)=>({$:'EAnd',left,right}),o=(left,right)=>({$:'EOr',left,right});
const meta=id=>({$:'Meta',id}), pn=expr=>({$:'PNot',expr}), pa=(left,right)=>({$:'PAnd',left,right}),po=(left,right)=>({$:'POr',left,right});
const demorgan=pn(pa(meta(0),meta(1))), replacement=po(pn(meta(0)),pn(meta(1)));
const original=o(n(a(v(0),v(1))),v(2));
const out=P.rewrite_all(original,demorgan,replacement);
assert.deepEqual(out,{$:'Built',expr:o(o(n(v(0)),n(v(1))),v(2))});
assert.equal(L.equivalent(3,original,out.expr).$,'Equivalent');
assert.deepEqual(P.rewrite_all(a(v(0),v(0)),pa(meta(0),meta(0)),meta(0)),{$:'Built',expr:v(0)});
assert.deepEqual(P.rewrite_all(a(v(0),v(1)),pa(meta(0),meta(0)),meta(0)),{$:'Built',expr:a(v(0),v(1))});
assert.deepEqual(P.rewrite_all(v(0),meta(0),meta(1)),{$:'TemplateInvalid'});
assert.deepEqual(P.rewrite_all(v(0),meta(4),meta(0)),{$:'TemplateInvalid'});
console.log('metavariable rewrite tests passed');
assert.deepEqual(P.rewrite_all(v(0),pa(meta(4),meta(0)),meta(0)),{$:'TemplateInvalid'});
assert.deepEqual(P.rewrite_all(v(0),{$:'PTrue'},meta(0)),{$:'TemplateInvalid'});
console.log('invalid pattern boundaries passed');
assert.deepEqual(P.rewrite_checked(3,original,demorgan,replacement),{$:'GateAccepted',expr:out.expr});
assert.deepEqual(P.rewrite_checked(1,v(0),meta(0),pn(meta(0))),{$:'GateRejected',assignment:0});
assert.deepEqual(P.rewrite_checked(1,v(0),meta(0),meta(1)),{$:'GateInvalid'});
assert.deepEqual(P.rewrite_checked(0,v(0),meta(0),meta(0)),{$:'GateInvalid'});
console.log('pattern rewrite gate tests passed');
const double=pn(pn(meta(0))), x4=n(n(n(n(v(0)))));
assert.deepEqual(P.repeat_checked(1,4,x4,double,meta(0)),{$:'GateRepeatDone',expr:v(0),steps:2});
assert.deepEqual(P.repeat_checked(1,2,v(0),meta(0),pn(meta(0))),{$:'GateRejected',assignment:0});
assert.deepEqual(P.repeat_checked(1,0,x4,double,meta(0)),{$:'GateRepeatLimit',expr:x4,steps:0});
console.log('repeated gated pattern rewriting passed');
