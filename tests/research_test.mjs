import assert from 'node:assert/strict';
import R from '../build/Research.mjs';
const T={$:'ETrue'}, F={$:'EFalse'};
const v=id=>({$:'EVar',id});
const a=(left,right)=>({$:'EAnd',left,right});
const n=expr=>({$:'ENot',expr});
const choices=(a,b,c,d)=>({$:'Choices',a,b,c,d});
const empty={$:'EmptySlot'};
const entry=(domain,bits,context,value)=>({$:'CacheEntry',domain,bits,context,value});
const slots=(a,b,c,d)=>({$:'CacheSlots',a,b,c,d});
const expr=a(v(0),T);
assert.deepEqual(R.lookup(1,expr,7,slots(entry(1,2,7,42),empty,empty,empty)),{$:'CacheHit',value:42});
assert.equal(R.lookup(1,expr,8,slots(entry(1,2,7,42),empty,empty,empty)).$,'CacheMiss');
assert.equal(R.lookup(2,expr,7,slots(entry(1,2,7,42),empty,empty,empty)).$,'CacheMiss');
assert.equal(R.lookup(1,v(1),7,slots(empty,empty,empty,empty)).$,'ResearchInvalid');
const base=a(T,v(0));
assert.deepEqual(R.improve(1,base,choices(v(0),F,n(n(v(0))),T)),{$:'Improved',index:0,cost:1});
assert.deepEqual(R.improve(1,v(0),choices(T,F,n(v(0)),a(T,v(0)))),{$:'NoImprovement'});
assert.equal(R.improve(1,v(0),choices(v(1),F,T,T)).$,'ResearchInvalid');
console.log('cache and gated improvement tests passed');
const node=(id,kind,status)=>({$:'EvidenceNode',id,kind,status});
const eg=(n,n0,n1,n2,n3,supports,contradicts)=>({$:'EvidenceGraph',n,n0,n1,n2,n3,supports,contradicts});
const g=eg(3,node(101,1,1),node(202,2,1),node(303,0,0),node(0,0,0),2+64,4);
assert.deepEqual(R.evidence_validate(g),{$:'EvidenceValid'});
assert.deepEqual(R.support_path(g,0,2),{$:'EvidencePath',length:2,nodes:36});
assert.deepEqual(R.contradicts(g,0,2),{$:'EvidenceLinked'});
assert.deepEqual(R.contradicts(g,2,0),{$:'EvidenceUnlinked'});
assert.equal(R.evidence_validate(eg(2,node(1,0,0),node(1,1,0),node(0,0,0),node(0,0,0),0,0)).$,'ResearchInvalid');
console.log('evidence graph tests passed');
const certified=R.certified_improve(1,base,choices(v(0),F,n(n(v(0))),T));
assert.deepEqual(certified,{$:'CertifiedImprovement',index:0,cost:1,expr:v(0),certificate:{$:'TruthCertificate',domain:1,bits:2}});
assert.equal(R.certified_improve(6,base,choices(v(0),F,T,T)).$,'ResearchInvalid');
assert.equal(R.certified_improve(1,v(0),choices(T,F,n(v(0)),a(T,v(0)))).$,'NoImprovement');
console.log('certificate-carrying optimization tests passed');
