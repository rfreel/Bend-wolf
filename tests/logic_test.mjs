import assert from 'node:assert/strict';
import L from '../build/Logic.mjs';
const T = {$:'ETrue'}, F = {$:'EFalse'};
const v = id => ({$: 'EVar', id});
const n = expr => ({$: 'ENot', expr});
const a = (left,right) => ({$: 'EAnd', left,right});
const o = (left,right) => ({$: 'EOr', left,right});
const tag = r => r.$;
assert.equal(L.eval(T,0), true);
assert.equal(L.eval(F,0), false);
assert.equal(L.eval(a(v(0),n(v(1))),1), true);
assert.equal(L.eval(a(v(0),n(v(1))),3), false);
assert.equal(tag(L.satisfy(2,a(v(0),n(v(0))))), 'Unsat');
assert.deepEqual(L.satisfy(2,a(v(0),n(v(1)))), {$:'Sat', assignment:1});
assert.equal(tag(L.satisfy(0,T)), 'Sat');
assert.equal(tag(L.satisfy(0,F)), 'Unsat');
assert.equal(tag(L.satisfy(0,v(0))), 'Invalid');
assert.equal(tag(L.satisfy(17,T)), 'Invalid');
assert.equal(tag(L.equivalent(2,n(a(v(0),v(1))),o(n(v(0)),n(v(1))))), 'Equivalent');
assert.deepEqual(L.equivalent(1,v(0),T), {$:'Different',assignment:0});
assert.equal(tag(L.equivalent(1,v(1),T)), 'Invalid');
assert.equal(L.eval(L.substitute(a(v(0),v(1)),0,n(v(1))),2), false);
assert.equal(L.eval(L.substitute(a(v(0),v(1)),0,T),2), true);
console.log('logic tests passed');
const ex=L.exists(a(v(0),v(1)),0);
const all=L.forall(a(v(0),v(1)),0);
assert.equal(L.equivalent(2,ex,v(1)).$,'Equivalent');
assert.equal(L.equivalent(2,all,F).$,'Equivalent');
assert.deepEqual(L.minimal_core4(2,v(0),n(v(0)),v(1),T),{$:'Core',mask:3});
assert.deepEqual(L.minimal_core4(2,v(0),v(1),T,T),{$:'NoCore'});
assert.deepEqual(L.minimal_core4(1,v(1),T,T,T),{$:'CoreInvalid'});
console.log('quantifier and inconsistent core tests passed');
assert.deepEqual(L.propagate(2,a(v(0),n(v(1)))),{$:'Propagated',must_true:1,must_false:2});
assert.deepEqual(L.propagate(2,o(v(0),v(1))),{$:'Propagated',must_true:0,must_false:0});
assert.equal(L.propagate(1,a(v(0),n(v(0)))).$,'PropagationUnsat');
assert.equal(L.propagate(13,T).$,'PropagationInvalid');
console.log('constraint propagation tests passed');
const all16=Array.from({length:16},(_,i)=>v(i)).reduce((x,y)=>a(x,y),T);
assert.deepEqual(L.satisfy(16,all16),{$:'Sat',assignment:65535});
assert.deepEqual(L.satisfy(16,n(all16)).assignment,0);
console.log('maximum Boolean domain boundary passed');
