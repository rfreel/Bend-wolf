import assert from 'node:assert/strict';
import R from '../build/Rewrite.mjs';
import P from '../build/Proof.mjs';
import L from '../build/Logic.mjs';
const T={$:'ETrue'}, F={$:'EFalse'};
const v=id=>({$:'EVar',id});
const n=expr=>({$:'ENot',expr});
const a=(left,right)=>({$:'EAnd',left,right});
const o=(left,right)=>({$:'EOr',left,right});
const term=a(T,o(F,n(n(v(0)))));
assert.deepEqual(R.simplify(term),v(0));
assert.equal(P.check(1,term,R.simplify(term)).$, 'Equivalent');
assert.deepEqual(P.check(1,v(0),T), {$:'Different',assignment:0});
assert.equal(P.check(0,v(0),T).$, 'Invalid');
assert.equal(P.under(1,v(0),v(0),T).$, 'Equivalent');
assert.deepEqual(P.under(1,T,v(0),T), {$:'Different',assignment:0});
assert.equal(P.under(0,v(0),T,T).$, 'Invalid');
const key=R.truth_table(2,a(v(0),n(v(1))));
assert.deepEqual(key, {$: 'TruthKey', bits:2});
assert.deepEqual(R.truth_table(0,T),{$: 'TruthKey',bits:1});
assert.deepEqual(R.truth_table(6,T),{$:'KeyInvalid'});
assert.deepEqual(R.truth_table(1,v(1)),{$:'KeyInvalid'});
assert.equal(L.eval(R.simplify(a(v(0),F)),1),false);
console.log('rewrite and certificate tests passed');
const cert={$:'TruthCertificate',domain:1,bits:2};
assert.deepEqual(P.verify_certificate(1,v(0),a(T,v(0)),cert),{$:'CertificateAccepted'});
assert.deepEqual(P.verify_certificate(1,v(0),T,cert),{$:'CertificateRejected'});
assert.deepEqual(P.verify_certificate(1,v(0),v(0),{$:'TruthCertificate',domain:1,bits:3}),{$:'CertificateRejected'});
assert.deepEqual(P.verify_certificate(2,v(0),v(0),cert),{$:'CertificateRejected'});
assert.deepEqual(P.verify_certificate(1,v(1),v(1),cert),{$:'CertificateInvalid'});
console.log('truth-table certificate tests passed');
const before=a(v(0),T), after=v(0), nested=o(before,F);
assert.equal(R.expr_equal(before,before),true);
assert.equal(R.expr_equal(before,after),false);
assert.deepEqual(R.replace_all(nested,before,after),o(v(0),F));
assert.deepEqual(R.repeat(3,nested,before,after),{$:'RewriteDone',expr:o(v(0),F),steps:1});
assert.deepEqual(R.repeat(2,v(0),v(0),n(v(0))),{$:'RewriteLimit',expr:n(n(v(0))),steps:2});
assert.equal(R.repeat(17,T,T,F).$,'RewriteInvalid');
console.log('ground rewrite tests passed');
