import assert from 'node:assert/strict';
import A from '../build/Arithmetic.mjs';
const c=value=>({$:'AConst',value});
const x={$:'AVar'};
const plus=(left,right)=>({$:'APlus',left,right});
const mul=(left,right)=>({$:'AMul',left,right});
const cube=mul(mul(plus(x,c(1)),plus(x,c(1))),plus(x,c(1)));
assert.deepEqual(A.polynomial(cube),{$:'Polynomial',c0:1,c1:3,c2:3,c3:1});
for(let n=0;n<=5;n++) assert.equal(A.eval(cube,n),[1,8,27,64,125,216][n]);
assert.equal(A.eval(plus(c(4294967295),c(1)),0),0);
assert.deepEqual(A.solve_eq(mul(x,x),c(9),10),{$:'Root',value:3});
assert.equal(A.solve_eq(mul(x,x),c(2),10).$,'NoRoot');
assert.equal(A.solve_eq(x,c(1),100001).$,'ArithInvalid');
assert.equal(A.polynomial(mul(cube,x)).$,'DegreeOverflow');
console.log('arithmetic tests passed');
const differenceOfSquares={$:'Polynomial',c0:4294967295,c1:0,c2:1,c3:0};
assert.deepEqual(A.factor_monic(differenceOfSquares,10),{$:'Factorization',root:1,q0:1,q1:1,q2:0});
assert.equal(A.factor_monic({$:'Polynomial',c0:1,c1:0,c2:1,c3:0},10).$,'NoRoot');
assert.equal(A.factor_monic(differenceOfSquares,100001).$,'ArithInvalid');
console.log('bounded modular factoring tests passed');
const exact=(c0,c1,c2,c3)=>({$:'ExactPolynomial',c0,c1,c2,c3});
assert.deepEqual(A.exact_roots(exact(0,0,1,0),exact(1,0,0,0),10),{$:'ExactRoots',first:1,count:1});
assert.deepEqual(A.exact_roots(exact(0,0,1,0),exact(2,0,0,0),10),{$:'ExactNoRoot'});
assert.deepEqual(A.exact_roots(exact(0,0,0,0),exact(0,0,0,0),10),{$:'ExactRoots',first:0,count:11});
assert.equal(A.exact_roots(exact(1001,0,0,0),exact(0,0,0,0),10).$,'ExactInvalid');
assert.equal(A.exact_roots(exact(0,0,1,0),exact(1,0,0,0),1001).$,'ExactInvalid');
console.log('bounded exact polynomial equation tests passed');
assert.deepEqual(A.exact_roots(exact(2,0,1,0),exact(0,3,0,0),1000),{$:'ExactRoots',first:1,count:2});
assert.equal(A.exact_eval(exact(1000,1000,1000,1000),1000),1001001001000);
assert.deepEqual(A.exact_factor(exact(0,0,1,0),exact(1,0,0,0),10),{$:'ExactFactor',root:1,q0p:1,q0n:0,q1p:1,q1n:0,q2p:0,q2n:0});
assert.equal(A.exact_factor(exact(1,0,1,0),exact(0,0,0,0),10).$,'ExactNoRoot');
assert.equal(A.exact_factor(exact(1001,0,0,0),exact(0,0,0,0),10).$,'ExactInvalid');
console.log('exact signed polynomial factoring passed');
const ec=value=>({$:'ExactConst',value}), ex={$:'ExactVar'}, ea=(left,right)=>({$:'ExactAdd',left,right}), em=(left,right)=>({$:'ExactMul',left,right});
const exactCube=em(em(ea(ex,ec(1)),ea(ex,ec(1))),ea(ex,ec(1)));
assert.deepEqual(A.exact_expand(exactCube),{$:'ExactExpanded',poly:exact(1,3,3,1)});
assert.equal(A.exact_expand(em(exactCube,ex)).$,'ExpansionOverflow');
assert.equal(A.exact_expand(em(ec(1000),ec(2))).$,'ExpansionOverflow');
console.log('exact polynomial expansion passed');
